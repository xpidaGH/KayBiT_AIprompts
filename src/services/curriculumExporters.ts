import { CurriculumDocument, BreadcrumbItem } from '../types';
import { generateLanguageHtmlDocument } from './htmlGenerator';
import { SUPPORTED_LANGUAGES } from './aiGateway';

/**
 * Triggers a native browser file download using a Blob
 */
export function triggerBlobDownload(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}

/**
 * Exports curriculum document as a structured JSON file
 */
export function exportCurriculumAsJson(doc: CurriculumDocument): string {
  const exportPayload = {
    app: 'KayBiT_AIprompts',
    formatVersion: '1.0.0',
    exportedAt: new Date().toISOString(),
    document: {
      id: doc.id,
      subject: doc.subject,
      title: doc.title,
      subtitle: doc.subtitle,
      sourceType: doc.sourceType,
      createdAt: doc.createdAt,
      totalChapters: doc.chapters.length,
      chapters: doc.chapters.map((ch, idx) => ({
        chapterNumber: ch.numStr || String(idx + 1).padStart(2, '0'),
        id: ch.id,
        title: ch.title,
        topic: ch.topic,
        objective: ch.objective,
        prompt: ch.prompt,
        critique: ch.critique || null,
        improvedPrompt: ch.improvedPrompt || null,
        translations: ch.translations || {}
      }))
    }
  };

  const jsonString = JSON.stringify(exportPayload, null, 2);
  const filename = `${doc.subject || 'curriculum'}_data.json`;
  triggerBlobDownload(jsonString, filename, 'application/json;charset=utf-8');
  return filename;
}

/**
 * Exports curriculum document as a comprehensive GitHub-flavored Markdown file
 */
export function exportCurriculumAsMarkdown(
  doc: CurriculumDocument,
  langCode: string = 'en',
  breadcrumbs: BreadcrumbItem[] = []
): string {
  const langInfo = SUPPORTED_LANGUAGES.find((l) => l.code === langCode);
  const langName = langInfo ? `${langInfo.name} (${langInfo.code.toUpperCase()})` : langCode.toUpperCase();

  const lines: string[] = [];

  // Title & Metadata
  lines.push(`# ${doc.title}`);
  lines.push('');
  if (doc.subtitle) {
    lines.push(`> ${doc.subtitle}`);
    lines.push('');
  }
  lines.push(`- **Subject Code:** \`${doc.subject}\``);
  lines.push(`- **Target Language:** ${langName}`);
  lines.push(`- **Chapters Count:** ${doc.chapters.length}`);
  lines.push(`- **Export Date:** ${new Date().toLocaleDateString()}`);
  lines.push(`- **AI Generator:** KayBiT AI Studio Multi-Agent Curriculum`);
  lines.push('');
  lines.push('---');
  lines.push('');

  // Breadcrumbs navigation if available
  if (breadcrumbs.length > 0) {
    lines.push('## Integrated Curriculum Suite');
    lines.push('');
    lines.push(breadcrumbs.map((b) => `- [${b.label}](${b.href})`).join('\n'));
    lines.push('');
    lines.push('---');
    lines.push('');
  }

  // Table of Contents
  lines.push('## Table of Contents');
  lines.push('');
  doc.chapters.forEach((ch, idx) => {
    const num = ch.numStr || String(idx + 1).padStart(2, '0');
    const translation = langCode !== 'en' ? ch.translations?.[langCode] : null;
    const title = translation?.title || ch.title;
    const anchor = `chapter-${num.toLowerCase()}-${title.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`;
    lines.push(`${idx + 1}. [Chapter ${num}: ${title}](#${anchor})`);
  });
  lines.push('');
  lines.push('---');
  lines.push('');

  // Detailed Chapters
  doc.chapters.forEach((ch, idx) => {
    const num = ch.numStr || String(idx + 1).padStart(2, '0');
    const translation = langCode !== 'en' ? ch.translations?.[langCode] : null;
    const title = translation?.title || ch.title;
    const topic = translation?.topic || ch.topic;
    const objective = translation?.objective || ch.objective;

    lines.push(`### Chapter ${num}: ${title}`);
    lines.push('');
    lines.push(`**Topic & Focus:** ${topic}`);
    lines.push('');
    lines.push(`**Pedagogical Objective:** ${objective}`);
    lines.push('');
    lines.push('#### Standalone AI Prompt Specification:');
    lines.push('');
    lines.push('```markdown');
    lines.push(ch.prompt);
    lines.push('```');
    lines.push('');

    if (ch.critique) {
      lines.push('#### Critique & Optimization Audit:');
      lines.push('');
      lines.push(`> ${ch.critique}`);
      lines.push('');
    }

    if (ch.improvedPrompt) {
      lines.push('#### Refined AI Prompt:');
      lines.push('');
      lines.push('```markdown');
      lines.push(ch.improvedPrompt);
      lines.push('```');
      lines.push('');
    }

    lines.push('---');
    lines.push('');
  });

  // Footer
  lines.push(`*Generated by KayBiT AI Studio • Multilingual Curriculum Architecture*`);

  const mdContent = lines.join('\n');
  const filename = `${doc.subject || 'curriculum'}_${langCode}.md`;
  triggerBlobDownload(mdContent, filename, 'text/markdown;charset=utf-8');
  return filename;
}

/**
 * Exports curriculum document as a standalone interactive HTML file
 */
export function exportCurriculumAsHtml(
  doc: CurriculumDocument,
  langCode: string = 'en',
  breadcrumbs: BreadcrumbItem[] = []
): string {
  const htmlContent = generateLanguageHtmlDocument(doc, langCode, breadcrumbs);
  const filename = `${doc.subject || 'curriculum'}_${langCode}.html`;
  triggerBlobDownload(htmlContent, filename, 'text/html;charset=utf-8');
  return filename;
}
